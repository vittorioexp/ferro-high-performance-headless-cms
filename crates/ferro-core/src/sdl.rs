//! GraphQL schema (SDL) generated from a snapshot. It documents exactly what the
//! executor in `ferro-engine` serves, and can feed code generators
//! (`graphql-codegen --schema schema.graphql`).
//!
//! Naming follows Directus: a type per collection (same name), queries
//! `<c>`, `<c>_by_id`, `<c>_count`, mutations `create_<c>_item(s)`,
//! `update_<c>_item(s)`, `delete_<c>_item(s)`. Filters and payloads use the `JSON`
//! scalar with the same format as the REST API.

use std::collections::BTreeMap;
use std::fmt::Write;

use crate::model::*;
use crate::system::system_collections;

/// Collections visible to GraphQL: system ones first, then user ones.
pub fn graph_collections(snapshot: &Snapshot) -> Vec<(Collection, bool)> {
    let mut out: Vec<(Collection, bool)> = system_collections().into_iter().map(|c| (c, true)).collect();
    out.extend(snapshot.collections.iter().cloned().map(|c| (c, false)));
    out.sort_by(|a, b| a.0.name.cmp(&b.0.name));
    out
}

pub fn union_name(collection: &str, field: &str) -> String {
    format!("{collection}_{field}")
}

fn scalar(ty: FieldType) -> &'static str {
    match ty {
        FieldType::Integer | FieldType::BigInteger => "Int",
        FieldType::Float | FieldType::Decimal => "Float",
        FieldType::Boolean => "Boolean",
        FieldType::Json => "JSON",
        _ => "String",
    }
}

fn type_of(f: &Field, known: &BTreeMap<String, bool>, owner: &str) -> String {
    let base = match f.ty {
        FieldType::M2o | FieldType::File => match f.related_collection() {
            Some(t) if known.contains_key(t) => t.to_string(),
            _ => "String".to_string(),
        },
        FieldType::O2m | FieldType::M2m | FieldType::M2a | FieldType::Translations => match f.related_collection() {
            Some(t) if known.contains_key(t) => format!("[{t}!]"),
            _ => "[String!]".to_string(),
        },
        FieldType::M2aItem => {
            let allowed = f.relation.as_ref().map(|r| r.allowed.iter().filter(|a| known.contains_key(*a)).count()).unwrap_or(0);
            if allowed > 0 {
                union_name(owner, &f.name)
            } else {
                "JSON".to_string()
            }
        }
        other => scalar(other).to_string(),
    };
    if f.required && f.has_column() {
        format!("{base}!")
    } else {
        base
    }
}

pub fn sdl(snapshot: &Snapshot) -> String {
    let collections = graph_collections(snapshot);
    let known: BTreeMap<String, bool> = collections.iter().map(|(c, sys)| (c.name.clone(), *sys)).collect();
    let mut out = String::new();
    out.push_str("# Generated by Ferro. Filters, sort and payloads use the REST formats (JSON scalar).\n");
    out.push_str("scalar JSON\n\n");

    for (c, _) in &collections {
        let _ = writeln!(out, "type {} {{", c.name);
        out.push_str("  id: ID!\n");
        let implicit: &[Field] = if c.system_fields { system_fields_cache().as_slice() } else { &[] };
        for f in c.fields.iter().chain(implicit.iter()) {
            let _ = writeln!(out, "  {}: {}", f.name, type_of(f, &known, &c.name));
        }
        let translated = crate::translations::translated_fields(snapshot, c);
        if !translated.is_empty() {
            out.push_str("  # filled when the query passes `lang`: each from the first language that has a value\n");
            for f in &translated {
                // relations (a translated image) come back as the related id
                let ty = if f.ty.is_relational() { "ID".to_string() } else { scalar(f.ty).to_string() };
                let _ = writeln!(out, "  {}: {ty}", f.name);
            }
            out.push_str("  _language: String\n");
        }
        out.push_str("}\n\n");
        for f in c.fields.iter().filter(|f| f.ty == FieldType::M2aItem) {
            let allowed: Vec<&String> = f
                .relation
                .as_ref()
                .map(|r| r.allowed.iter().filter(|a| known.contains_key(*a)).collect())
                .unwrap_or_default();
            if !allowed.is_empty() {
                let members = allowed.iter().map(|a| a.as_str()).collect::<Vec<_>>().join(" | ");
                let _ = writeln!(out, "union {} = {}\n", union_name(&c.name, &f.name), members);
            }
        }
    }

    out.push_str("type Query {\n");
    for (c, _) in &collections {
        let n = &c.name;
        let has_lang = c.fields.iter().any(|f| f.ty == FieldType::Translations);
        let lang = if has_lang { ", lang: String" } else { "" };
        if c.meta.singleton {
            let _ = writeln!(out, "  {n}{}: {n}", if has_lang { "(lang: String)" } else { "" });
        } else {
            let _ = writeln!(out, "  {n}(filter: JSON, sort: [String], limit: Int, offset: Int, page: Int, search: String{lang}): [{n}!]!");
            let _ = writeln!(out, "  {n}_by_id(id: ID!{lang}): {n}");
            let _ = writeln!(out, "  {n}_count(filter: JSON, search: String): Int!");
        }
    }
    out.push_str("}\n\n");

    out.push_str("type delete_one {\n  id: ID!\n}\n\ntype delete_many {\n  ids: [ID!]!\n}\n\n");
    out.push_str("type Mutation {\n");
    for (c, sys) in &collections {
        if *sys {
            continue;
        }
        let n = &c.name;
        if c.meta.singleton {
            let _ = writeln!(out, "  update_{n}(data: JSON!): {n}");
        } else {
            let _ = writeln!(out, "  create_{n}_items(data: [JSON!]!): [{n}!]!");
            let _ = writeln!(out, "  create_{n}_item(data: JSON!): {n}");
            let _ = writeln!(out, "  update_{n}_items(ids: [ID!]!, data: JSON!): [{n}!]!");
            let _ = writeln!(out, "  update_{n}_item(id: ID!, data: JSON!): {n}");
            let _ = writeln!(out, "  delete_{n}_items(ids: [ID!]!): delete_many");
            let _ = writeln!(out, "  delete_{n}_item(id: ID!): delete_one");
        }
    }
    out.push_str("}\n");
    out
}

fn system_fields_cache() -> &'static Vec<Field> {
    use std::sync::OnceLock;
    static CACHE: OnceLock<Vec<Field>> = OnceLock::new();
    CACHE.get_or_init(system_fields)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_types_unions_and_roots() {
        let snap: Snapshot = serde_yaml::from_str(include_str!("../tests/fixtures/pages.yaml")).unwrap();
        let sdl = sdl(&snap);
        assert!(sdl.contains("scalar JSON"));
        assert!(sdl.contains("type pages {\n  id: ID!\n  title: String!\n"), "{sdl}");
        assert!(sdl.contains("  cover: ferro_files\n"));
        assert!(sdl.contains("  category: categories\n"));
        assert!(sdl.contains("  user_created: ferro_users\n"), "system fields are exposed");
        assert!(sdl.contains("  blocks: [pages_blocks!]\n"));
        assert!(sdl.contains("  item: pages_blocks_item\n"));
        assert!(sdl.contains("union pages_blocks_item = block_hero | block_text\n"));
        assert!(sdl.contains("  pages(filter: JSON, sort: [String], limit: Int, offset: Int, page: Int, search: String): [pages!]!\n"));
        assert!(sdl.contains("  pages_by_id(id: ID!): pages\n"));
        assert!(sdl.contains("  create_pages_item(data: JSON!): pages\n"));
        assert!(sdl.contains("  delete_pages_items(ids: [ID!]!): delete_many\n"));
        assert!(!sdl.contains("create_ferro_users"), "system collections are read-only");
        assert!(sdl.contains("  ferro_users_by_id(id: ID!): ferro_users\n"));
    }

    #[test]
    fn singleton_has_no_list() {
        let snap: Snapshot = serde_yaml::from_str("collections:\n  - name: settings\n    meta: { singleton: true }\n    fields:\n      - { name: site_name, type: string }\n").unwrap();
        let out = sdl(&snap);
        assert!(out.contains("  settings: settings\n"));
        assert!(out.contains("  update_settings(data: JSON!): settings\n"));
        assert!(!out.contains("settings_by_id"));
    }
}
